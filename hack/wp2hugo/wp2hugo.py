class Item:
    def __init__(self, el):
        t = lambda path: el.findtext(path, default='', namespaces=NS)  # noqa: E731
        self.id = t('wp:post_id')
        self.type = t('wp:post_type')
        self.status = t('wp:status')
        self.slug = t('wp:post_name')
        self.title = t('title').strip()
        self.date = iso_date(t('wp:post_date_gmt'), t('wp:post_date'))
        self.modified = iso_date(t('wp:post_modified_gmt'), t('wp:post_modified'))
        self.content = t('content:encoded')
        self.excerpt = t('excerpt:encoded')
        self.creator = t('dc:creator')
        self.parent = t('wp:post_parent')
        self.password = t('wp:post_password')
        self.attachment_url = t('wp:attachment_url')
        self.meta = {m.findtext('wp:meta_key', namespaces=NS): m.findtext('wp:meta_value', default='', namespaces=NS)
                     for m in el.findall('wp:postmeta', NS)}
        self.terms = [(c.get('domain'), c.get('nicename'), (c.text or '').strip()) for c in el.findall('category')]

    def m(self, key):
        return (self.meta.get(key) or '').strip()

    def terms_of(self, domain):
        return [(nice, name) for d, nice, name in self.terms if d == domain]


class Migrator:
    def __init__(self, wxr, content_dir, cache_dir):
        root = ET.parse(wxr).getroot().find('channel')
        self.items = [Item(el) for el in root.findall('item')]
        self.by_id = {i.id: i for i in self.items}
        self.attachments = {i.id: i.attachment_url for i in self.items if i.type == 'attachment'}
        self.categories = {c.findtext('wp:category_nicename', namespaces=NS): (
            c.findtext('wp:cat_name', namespaces=NS), c.findtext('wp:category_parent', namespaces=NS))
            for c in root.findall('wp:category', NS)}
        self.content = content_dir
        self.report = defaultdict(list)
        self.media = Media(cache_dir, self.attachments)
        self.conv = ContentConverter(self.media, self.attachments, self.report)
        self.stats = Counter()
        self.aliases = defaultdict(list)  # new url -> [old paths]
        for old, new in LEGACY_REDIRECTS.items():
            self.aliases[new].append(f'/{old}/')
        for new, olds in EXTRA_ALIASES.items():
            self.aliases[new].extend(olds)

    def published(self, *types):
        return [i for i in self.items if i.type in types and i.status == 'publish' and not i.password]

    def md(self, html, bundle, source):
        return self.conv.to_md(html, bundle, source)

    # -- ACF helpers
    def link(self, raw, bundle):
        data = php_unserialize(raw)
        if not isinstance(data, dict) or not data.get('url'):
            return None
        label, url = (data.get('title') or '').strip(), data['url'].strip()
        if ' ' in url and label.startswith('http'):  # swapped fields on the old links page
            label, url = url.split('://', 1)[-1], label
        if UPLOADS_RE.match(url):
            url = self.bundle_url(bundle) + self.media.add(bundle, url)
        return {'label': label or url, 'url': site_path(url)}

    def bundle_url(self, bundle):
        rel = bundle.relative_to(self.content).as_posix()
        return self.urls.get(rel, f'/{rel}/')

    def sections(self, item, bundle):
        layouts = php_unserialize(item.m('flexible_sections'))
        if not isinstance(layouts, dict):
            return []
        out = []
        for idx, layout in sorted(layouts.items()):
            p = f'flexible_sections_{idx}_'
            g = lambda key: item.m(p + key)  # noqa: E731
            tone = 'panel' if g('background_type') not in ('', 'none') else None
            src = f'{item.slug}#section{idx}'
            if layout in ('full_width', 'hero'):
                content = self.md(g('content') or g('hero_content'), bundle, src)
                if content:
                    out.append({'type': 'text', 'content': content, 'width': 'wide' if g('content_width') not in ('', 'narrow') else None, 'tone': tone})
            elif layout in ('fifty_fifity_columns', 'one_third_two_thirds_columns', 'callout_card'):
                media_type = g('media_column_type')
                cta = self.link(g('text_column_cta'), bundle)
                out.append({
                    'type': 'split',
                    'title': g('heading'),
                    'content': self.md(g('text_column'), bundle, src),
                    'content2': self.md(g('text_column_two'), bundle, src) if media_type not in ('image', 'video') else None,
                    'image': self.media.by_id(bundle, g('image')) if media_type == 'image' else None,
                    'video': g('youtube_video_share_link') if media_type == 'video' else None,
                    'ratio': 'third' if layout == 'one_third_two_thirds_columns' else None,
                    'reverse': g('section_orientation') == 'text-on-right',
                    'card': layout == 'callout_card',
                    'tone': tone,
                    'buttons': [cta] if cta else None,
                })
            elif layout == 'tabs':
                tabs = [{'title': g(f'tabs_{n}_tab_title'), 'content': self.md(g(f'tabs_{n}_panel_content'), bundle, src)}
                        for n in range(int(g('tabs') or 0))]
                out.append({'type': 'tabs', 'intro': self.md(g('tabs_intro_content'), bundle, src), 'tabs': tabs})
            elif layout == 'banner':
                out.append({'type': 'banner', 'text': g('banner_content'), 'button': self.link(g('cta'), bundle)})
            elif layout == 'sponsors_sectiion':
                out.append({'type': 'sponsors', 'intro': self.md(g('intro_text'), bundle, src), **DEFAULT_SPONSORS_SECTION})
            elif layout in ('staff', 'speakers_section'):
                key = 'staff_members' if layout == 'staff' else 'speakers'
                people = []
                for n in range(int(g(key) or 0)):
                    q = f'{key}_{n}_'
                    people.append({
                        'name': g(q + 'name'),
                        'role': g(q + 'title'),
                        'image': self.media.by_id(bundle, g(q + 'image')),
                        'bio': self.conv.plain(g(q + 'bio')),
                        'links': {'linkedin': g(q + 'linkedin_link'), 'x': g(q + 'twitter_link'), 'website': g(q + 'website')},
                    })
                out.append({'type': 'people', 'intro': self.md(g('intro_text'), bundle, src), 'people': people})
            else:
                self.report['unknown layouts'].append(f'{item.slug}: {layout}')
        return out

    # -- content types
    def posts(self):
        for item in self.published('post'):
            bundle = self.content / 'blog' / item.slug
            cats = [self.categories.get(nice, (name, ''))[0] or name for nice, name in item.terms_of('category')]
            cats = [c for c in cats if c.lower() != 'uncategorized']
            fm = {
                'title': item.title,
                'date': item.date,
                'lastmod': item.modified,
                'slug': item.slug,
                'author': AUTHORS.get(item.creator),
                'description': self.conv.plain(item.excerpt, 200) or None,
                'image': self.media.by_id(bundle, item.m('_thumbnail_id')),
                'hideImage': item.m('hide_featured_image') == '1',
                'categories': cats,
                'tags': [term_name(name) for _, name in item.terms_of('post_tag')],
            }
            yield bundle, fm, self.md(item.content, bundle, item.slug), item

    def newsroom(self):
        for item in self.published('newsroom_posts'):
            bundle = self.content / 'newsroom' / item.slug
            fm = {
                'title': item.title,
                'date': item.date,
                'slug': item.slug,
                'location': item.m('location').title() if item.m('location').isupper() else item.m('location'),
                'description': self.conv.plain(item.m('excerpt'), 200),
                'image': self.media.by_id(bundle, item.m('_thumbnail_id')),
            }
            yield bundle, fm, self.md(item.content, bundle, item.slug), item

    def events(self):
        for item in self.published('dok_events_posts'):
            bundle = self.content / 'dok-events' / item.slug
            etype = item.m('event_type') or 'other'
            self.report['event types'].append(etype)
            fm = {
                'title': item.title,
                'date': item.date,
                'slug': item.slug,
                'eventType': etype if etype in EVENT_TYPES else 'other',
                'eventStart': acf_date(item.m('event_start_date')),
                'eventEnd': acf_date(item.m('event_end_date')),
                'location': item.m('location'),
                'registerURL': item.m('meetup_link'),
                'image': self.media.by_id(bundle, item.m('_thumbnail_id')),
                'sections': self.sections(item, bundle),
            }
            # single-dok_events_posts.php renders only the page-builder sections, never the post body.
            yield bundle, fm, '', item

    def resources(self):
        for item in self.published('resources_posts'):
            bundle = self.content / 'resources' / item.slug
            types = [nice for nice, _ in item.terms_of('resources')]
            link = item.m('link')
            if UPLOADS_RE.match(link):
                link = f'/resources/{item.slug}/' + self.media.add(bundle, link)
            fm = {
                'title': item.title,
                'date': item.date,
                'slug': item.slug,
                'resourceType': types[0] if types else 'article',
                'link': site_path(link),
                'credit': item.m('credit'),
                'description': self.conv.plain(item.m('description')),
                'image': self.media.by_id(bundle, item.m('_thumbnail_id')),
            }
            yield bundle, fm, self.md(item.content, bundle, item.slug), item

    def pages(self):
        for item in self.published('page'):
            slug = item.slug
            if slug in SKIP_PAGES or slug in SECTION_PAGES or slug in LEGACY_REDIRECTS or slug in LEGACY_TO_SECTIONS:
                continue
            template = item.m('_wp_page_template')
            parent = self.by_id.get(item.parent)
            if template == REPORT_TEMPLATE:
                bundle = self.content / 'dok-reports' / slug
                self.urls[bundle.relative_to(self.content).as_posix()] = f'/{slug}/'
                body = self.md(item.m('report_content'), bundle, slug)
                fm = {
                    'title': item.title,
                    'date': item.date,
                    'url': f'/{slug}/',
                    'cover': self.media.by_id(bundle, item.m('download_image')),
                    'pdf': self.media.by_id(bundle, item.m('download_file')),
                }
                yield bundle, fm, body, item
                continue
            name = f'{parent.slug}-{slug}' if parent and parent.id != '0' else slug
            bundle = self.content / name
            url = f'/{parent.slug}/{slug}/' if parent and parent.id != '0' else None
            if url:
                self.urls[name] = url
            fm = {'title': item.title, 'date': item.date, 'url': url}
            if template == LINKTREE_TEMPLATE:
                fm['layout'] = 'links'
                fm['links'] = [l for n in range(int(item.m('links') or 0)) if (l := self.link(item.m(f'links_{n}_link'), bundle))]
                body = self.conv.plain(item.content)
            else:
                fm['sections'] = self.sections(item, bundle)
                # page-flex-template.php renders only the sections; its post body is stale pre-builder content.
                body = '' if template == FLEX_TEMPLATE else self.md(item.content, bundle, slug)
                first = fm['sections'][0] if fm['sections'] else {}
                if re.match(r'#\s', (first.get('content') or '')) or re.match(r'#\s', body):
                    fm['hideTitle'] = True
            yield bundle, fm, body, item

    def taxonomies(self):
        """Term pages with display names and aliases for the old WordPress term URLs."""
        for taxonomy in ('categories', 'tags'):
            shutil.rmtree(self.content / taxonomy, ignore_errors=True)
        for nice, (name, parent) in self.categories.items():
            if nice == 'uncategorized':
                continue
            key = urlize(name)
            # WordPress served child categories at both the nested and the flat URL.
            olds = {f'/blog/category/{parent}/{nice}/' if parent else None, f'/blog/category/{nice}/'}
            fm = {'title': name, 'aliases': sorted(o for o in olds if o and o != f'/blog/category/{key}/')}
            write_page(self.content / 'categories' / key / '_index.md', fm)
        seen = set()
        for item in self.published('post'):
            for nice, name in item.terms_of('post_tag'):
                name = term_name(name)
                key = urlize(name)
                if key in seen:
                    continue
                seen.add(key)
                fm = {'title': name}
                if nice != key:
                    fm['aliases'] = [f'/blog/tag/{nice}/']
                write_page(self.content / 'tags' / key / '_index.md', fm)

    # -- run
    def run(self):
        self.urls = {}
        generated = []
        for producer in (self.posts, self.newsroom, self.events, self.resources, self.pages):
            for bundle, fm, body, item in producer():
                generated.append((bundle, fm, body))
                self.stats[item.type] += 1
        for bundle, fm, body in generated:
            if bundle.exists():
                shutil.rmtree(bundle)
            bundle.mkdir(parents=True)
        self.media.sync()
        for bundle, fm, body in generated:
            for name in self.media.missing(bundle):
                fm, body = strip_file(fm, name), strip_file(body, name)
            url = fm.get('url') or self.bundle_url(bundle)
            if self.aliases.get(url):
                fm['aliases'] = self.aliases[url]
            write_page(bundle / 'index.md', fm, body)
        self.taxonomies()
        print('Generated:', dict(self.stats))
        if self.media.failed:
            print(f'Media failures: {len(self.media.failed)}')
        for key, values in self.report.items():
            print(f'{key}:', dict(Counter(values)) if key == 'event types' else '')
            if key != 'event types':
                for v in values:
                    print('  ', v)


