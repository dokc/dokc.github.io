class Media:
    """Collects upload URLs per bundle, then downloads them in parallel and copies into bundles."""

    def __init__(self, cache_dir, attachments):
        self.cache = cache_dir
        self.attachments = attachments  # id -> url
        self.wanted = defaultdict(dict)  # bundle -> {url: filename}
        self.failed = set()

    def by_id(self, bundle, attachment_id):
        url = self.attachments.get(str(attachment_id or '').strip())
        return self.add(bundle, url) if url else None

    def add(self, bundle, url):
        url = normalize_upload(url)
        names = self.wanted[bundle]
        if url in names:
            return names[url]
        name = urllib.parse.unquote(Path(urllib.parse.urlparse(url).path).name)
        name = re.sub(r'[^\w.-]+', '-', name)
        if name in names.values():
            name = hashlib.sha1(url.encode()).hexdigest()[:6] + '-' + name
        names[url] = name
        return name

    def missing(self, bundle):
        return [name for url, name in self.wanted.get(bundle, {}).items() if url in self.failed]

    def _cache_path(self, url):
        return self.cache / urllib.parse.urlparse(url).path.lstrip('/')

    def _download(self, url):
        dest = self._cache_path(url)
        if dest.exists() and dest.stat().st_size:
            return url, True
        dest.parent.mkdir(parents=True, exist_ok=True)
        try:
            req = urllib.request.Request(urllib.parse.quote(url, safe=':/%?=&'), headers={'User-Agent': USER_AGENT})
            with urllib.request.urlopen(req, timeout=60) as resp, open(dest, 'wb') as out:
                shutil.copyfileobj(resp, out)
            return url, True
        except Exception as exc:  # noqa: BLE001 - report and continue
            print(f'  ! download failed {url}: {exc}', file=sys.stderr)
            dest.unlink(missing_ok=True)
            return url, False

    def sync(self):
        urls = sorted({u for names in self.wanted.values() for u in names})
        print(f'Media: {len(urls)} files')
        with ThreadPoolExecutor(max_workers=8) as pool:
            for url, ok in pool.map(self._download, urls):
                if not ok:
                    self.failed.add(url)
        for bundle, names in self.wanted.items():
            for url, name in names.items():
                if url not in self.failed:
                    shutil.copyfile(self._cache_path(url), bundle / name)


