def php_unserialize(value):
    """Minimal PHP unserialize for the arrays ACF stores (strings, ints, bools, nested arrays)."""
    if not value or not value.startswith(('a:', 's:', 'i:', 'b:', 'N;')):
        return value
    data = value.encode('utf-8')
    pos = 0

    def parse():
        nonlocal pos
        kind = chr(data[pos])
        if kind == 'N':
            pos += 2
            return None
        if kind in 'ibd':
            end = data.index(b';', pos)
            raw = data[pos + 2:end].decode()
            pos = end + 1
            return int(raw) if kind == 'i' else (raw == '1' if kind == 'b' else float(raw))
        if kind == 's':
            colon = data.index(b':', pos + 2)
            length = int(data[pos + 2:colon])
            raw = data[colon + 2:colon + 2 + length].decode('utf-8', 'replace')
            pos = colon + 2 + length + 2
            return raw
        if kind == 'a':
            colon = data.index(b':', pos + 2)
            count = int(data[pos + 2:colon])
            pos = colon + 2
            out = {}
            for _ in range(count):
                key = parse()
                out[key] = parse()
            pos += 1
            return out
        raise ValueError(f'unsupported PHP type {kind!r}')

    try:
        return parse()
    except (ValueError, IndexError):
        return value


def urlize(text):
    """Approximates Hugo's urlize for taxonomy term keys."""
    text = re.sub(r'[^\w\s-]', '', text.lower(), flags=re.UNICODE).strip()
    return re.sub(r'[\s_]+', '-', text)


def term_name(name):
    """Hugo keeps '/' in term URLs ("CI/CD" -> /tag/ci/cd/), so swap it for a dash."""
    return name.replace('/', '-')


def iso_date(gmt, local):
    value = gmt if gmt and not gmt.startswith('0000') else local
    return value.replace(' ', 'T') + 'Z'


def acf_date(value):
    if value and re.fullmatch(r'\d{8}', value):
        return f'{value[:4]}-{value[4:6]}-{value[6:]}'
    return None


def site_path(url):
    """https://dok.community/foo/ -> /foo/ ; other URLs unchanged."""
    parsed = urllib.parse.urlparse(url)
    if parsed.netloc.lower() in SITE_HOSTS and '/wp-content/uploads/' not in parsed.path:
        path = parsed.path or '/'
        if not path.endswith('/') and '.' not in path.rsplit('/', 1)[-1]:
            path += '/'
        path = LINK_REWRITES.get(path, path)
        return path + (('?' + parsed.query) if parsed.query else '') + (('#' + parsed.fragment) if parsed.fragment else '')
    if not parsed.netloc and parsed.path in LINK_REWRITES:
        return LINK_REWRITES[parsed.path]
    return url


def normalize_upload(url):
    url = url.replace('&amp;', '&').strip()
    if url.startswith('//'):
        url = 'https:' + url
    url = re.sub(r'^http://', 'https://', url)
    url = url.replace('://www.dok.community', '://dok.community')
    return url.split('?')[0].split('#')[0].rstrip('.,;')


class LiteralDumper(yaml.SafeDumper):
    pass


def _str_representer(dumper, data):
    if '\n' in data:
        data = '\n'.join(line.rstrip() for line in data.strip('\n').split('\n')) + '\n'
        return dumper.represent_scalar('tag:yaml.org,2002:str', data, style='|')
    return dumper.represent_scalar('tag:yaml.org,2002:str', data)


LiteralDumper.add_representer(str, _str_representer)


def drop_empty(obj):
    if isinstance(obj, dict):
        return {k: drop_empty(v) for k, v in obj.items() if v not in (None, '', [], {}, False)}
    if isinstance(obj, list):
        return [drop_empty(v) for v in obj if v not in (None, '', [], {})]
    return obj


def strip_file(value, name):
    """Removes images and unlinks links pointing at a bundle file that could not be downloaded."""
    if isinstance(value, dict):
        return {k: (None if v == name else strip_file(v, name)) for k, v in value.items()}
    if isinstance(value, list):
        return [strip_file(v, name) for v in value]
    if isinstance(value, str):
        value = re.sub(rf'!\[[^\]]*\]\({re.escape(name)}[^)]*\)', '', value)
        return re.sub(rf'\[(!\[[^\]]*\]\([^)]*\)|[^\]]*)\]\({re.escape(name)}\)', r'\1', value)
    return value


def write_page(path, front_matter, body=''):
    path.parent.mkdir(parents=True, exist_ok=True)
    fm = yaml.dump(drop_empty(front_matter), Dumper=LiteralDumper, sort_keys=False, allow_unicode=True, width=10_000)
    path.write_text(f'---\n{fm}---\n' + (f'\n{body.strip()}\n' if body.strip() else ''), encoding='utf-8')


