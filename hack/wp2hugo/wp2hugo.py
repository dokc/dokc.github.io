class Converter(MarkdownConverter):
    def convert_img(self, el, text, parent_tags):
        alt = (el.get('alt') or '').replace('"', "'").strip()
        title = (el.get('title') or '').replace('"', "'").strip()
        src = el.get('src') or ''
        return f'![{alt}]({src}' + (f' "{title}"' if title else '') + ')'


def wpautop(html):
    """Light version of WordPress wpautop: blank-line separated text becomes paragraphs."""
    if '\n' not in html:
        return html
    block = re.compile(r'^\s*<(p|div|h[1-6]|ul|ol|li|table|thead|tbody|tr|td|th|blockquote|pre|figure|iframe|script|form|hr|section|center|dl|style|WP2HUGO)', re.I)
    out = []
    for chunk in re.split(r'\n\s*\n', html.replace('\r\n', '\n')):
        if not chunk.strip():
            continue
        if block.match(chunk):
            out.append(chunk)
        else:
            out.append('<p>' + re.sub(r'(?<!>)\n(?!\s*<)', '<br>\n', chunk.strip()) + '</p>')
    return '\n\n'.join(out)


class ContentConverter:
    def __init__(self, media, attachments, report):
        self.media = media
        self.attachments = attachments
        self.report = report

    # -- shortcodes
    def _decode_code(self, text):
        text = text.strip()
        try:
            decoded = base64.b64decode(text, validate=True).decode('utf-8')
            if decoded.isprintable() or '\n' in decoded:
                return decoded
        except (binascii.Error, UnicodeDecodeError, ValueError):
            pass
        return text

    def _embed(self, store, html):
        store.append(html)
        return f'\n\n<p>WP2HUGOEMBED{len(store) - 1}X</p>\n\n'

    @staticmethod
    def _video_html(video_id):
        return f'<div class="video"><iframe src="https://www.youtube-nocookie.com/embed/{video_id}" title="YouTube video" loading="lazy" allow="accelerometer; clipboard-write; encrypted-media; gyroscope; picture-in-picture" allowfullscreen></iframe></div>'

    def _video(self, store, video_id):
        return self._embed(store, self._video_html(video_id))

    def shortcodes(self, html, store):
        def attr(attrs, name):
            m = re.search(rf'{name}="([^"]*)"', attrs)
            return m.group(1) if m else ''

        def caption(m):
            inner = m.group(2)
            img = re.search(r'<img[^>]*>', inner)
            text = re.sub(r'<img[^>]*>|</?a[^>]*>', '', inner).strip()
            if not img:
                return inner
            tag = img.group(0)
            if text:
                tag = re.sub(r'<img', f'<img title="{BeautifulSoup(text, "html.parser").get_text(" ", strip=True)}"', tag, count=1)
            return tag

        def embed(m):
            url = m.group(1).strip()
            yt = YOUTUBE_RE.search(url)
            return self._video(store, yt.group(1)) if yt else f'<p><a href="{url}">{url}</a></p>'

        def gallery(m):
            ids = attr(m.group(1), 'ids').split(',')
            imgs = ''.join(f'<p><img src="{self.attachments[i.strip()]}" alt=""></p>' for i in ids if i.strip() in self.attachments)
            return imgs

        def sessionize(m):
            sid = attr(m.group(1), 'id')
            kind = attr(m.group(1), 'embed_type') or 'GridSmart'
            return self._embed(store, f'<script type="text/javascript" src="https://sessionize.com/api/v2/{sid}/view/{kind}"></script>')

        html = re.sub(r'\[caption([^\]]*)\](.*?)\[/caption\]', caption, html, flags=re.S)
        html = re.sub(r'\[embed[^\]]*\](.*?)\[/embed\]', embed, html, flags=re.S)
        html = re.sub(r'\[gallery([^\]]*)\]', gallery, html)
        html = re.sub(r'\[sessionize([^\]]*)\]', sessionize, html)
        html = re.sub(r'\[ninja_form[^\]]*\]', '', html)
        # Avada/Fusion builder (2020 posts)
        html = re.sub(r'\[fusion_imageframe[^\]]*\](.*?)\[/fusion_imageframe\]',
                      lambda m: m.group(1) if '<img' in m.group(1) else f'<p><img src="{m.group(1).strip()}" alt=""></p>', html, flags=re.S)
        html = re.sub(r'\[fusion_title[^\]]*\](.*?)\[/fusion_title\]', r'<h2>\1</h2>', html, flags=re.S)
        html = re.sub(r'\[fusion_separator[^\]]*\](\[/fusion_separator\])?', '<hr>', html)
        html = re.sub(r'\[fusion_(?:syntax_highlighter|code)([^\]]*)\](.*?)\[/fusion_(?:syntax_highlighter|code)\]',
                      lambda m: '<pre><code>' + self._decode_code(m.group(2)).replace('&', '&amp;').replace('<', '&lt;') + '</code></pre>', html, flags=re.S)
        html = re.sub(r'\[fusion_button([^\]]*)\](.*?)\[/fusion_button\]',
                      lambda m: f'<p><a href="{attr(m.group(1), "link")}">{m.group(2)}</a></p>', html, flags=re.S)
        html = re.sub(r'\[fusion_blog[^\]]*\](\[/fusion_blog\])?', '', html)
        html = re.sub(r'\[/?fusion_[a-z_]+[^\]]*\]', '\n\n', html)
        return html

    # -- main entry
    def to_md(self, html, bundle, source):
        if not html or not html.strip():
            return ''
        store = []
        html = re.sub(r'<!--.*?-->', '', html, flags=re.S)
        html = self.shortcodes(html, store)
        html = wpautop(html)
        soup = BeautifulSoup(html, 'html.parser')

        for c in soup.find_all(string=lambda s: isinstance(s, Comment)):
            c.extract()
        for tag in soup.find_all(['style', 'noscript', 'form', 'input', 'button', 'label', 'fieldset', 'select', 'textarea']):
            tag.decompose()
        for tag in soup.find_all('script'):
            src = tag.get('src') or ''
            if 'gist.github.com' in src:
                gist = src.removesuffix('.js')
                tag.replace_with(BeautifulSoup(f'<p><a href="{gist}">{gist}</a></p>', 'html.parser'))
            else:
                tag.decompose()

        # Google Docs paste artifacts
        for tag in soup.find_all('b', style=re.compile(r'font-weight:\s*normal')):
            tag.unwrap()
        for tag in soup.find_all('span'):
            style = (tag.get('style') or '').replace(' ', '')
            if re.search(r'font-weight:(700|bold)', style) and tag.get_text(strip=True):
                tag.name = 'strong'
                tag.attrs = {}
            elif 'font-style:italic' in style and tag.get_text(strip=True):
                tag.name = 'em'
                tag.attrs = {}
            else:
                tag.unwrap()
        for tag in soup.find_all(['center', 'section', 'font']):
            tag.unwrap()
        # Line breaks inside code are plain newlines, not Markdown hard breaks.
        for pre in soup.find_all('pre'):
            for br in pre.find_all('br'):
                br.replace_with('\n')

        # WordPress oEmbed: a paragraph holding only a YouTube URL renders as a player.
        for p in soup.find_all('p'):
            text = p.get_text(strip=True)
            yt = YOUTUBE_RE.search(text) if re.fullmatch(r'https?://\S+', text) else None
            if yt and not p.find('img'):
                p.replace_with(BeautifulSoup(self._video(store, yt.group(1)), 'html.parser'))

        for iframe in soup.find_all('iframe'):
            src = iframe.get('src') or ''
            yt = YOUTUBE_RE.search(src)
            if yt:
                token = self._video(store, yt.group(1))
            else:
                src = site_path('https:' + src if src.startswith('//') else src)
                height = iframe.get('height') or '600'
                title = iframe.get('title') or 'Embedded content'
                token = self._embed(store, f'<iframe src="{src}" title="{title}" height="{height}" loading="lazy"></iframe>')
                self.report['iframes'].append(f'{source}: {src}')
            iframe.replace_with(BeautifulSoup(token, 'html.parser'))

        for img in soup.find_all('img'):
            src = img.get('src') or ''
            if UPLOADS_RE.match(src):
                img['src'] = self.media.add(bundle, src)
            img.attrs = {k: v for k, v in img.attrs.items() if k in ('src', 'alt', 'title')}
            parent = img.parent
            if parent and parent.name == 'a' and UPLOADS_RE.match(parent.get('href') or '') and re.search(r'\.(png|jpe?g|gif|webp)$', parent['href'], re.I):
                parent.unwrap()

        for a in soup.find_all('a'):
            href = (a.get('href') or '').strip()
            if UPLOADS_RE.match(href):
                a['href'] = self.media.add(bundle, href)
            elif href:
                a['href'] = site_path(href)
            a.attrs = {k: v for k, v in a.attrs.items() if k in ('href', 'title')}

        for p in soup.find_all('p'):
            if not p.get_text(strip=True) and not p.find(['img', 'iframe']):
                p.decompose()

        md = Converter(heading_style='ATX', bullets='-', escape_misc=False, newline_style='BACKSLASH').convert_soup(soup)
        md = md.replace('\u00a0', ' ')
        # oEmbed also applies to a YouTube URL alone on a line inside a paragraph.
        md = re.sub(r'^\s*(https?://\S*(?:youtu\.be|youtube\.com)\S*?)\\?\s*$',
                    lambda m: '\n' + self._video_html(yt.group(1)) + '\n' if (yt := YOUTUBE_RE.search(m.group(1))) else m.group(0),
                    md, flags=re.M)
        for i, snippet in enumerate(store):
            md = md.replace(f'WP2HUGOEMBED{i}X', f'\n\n{snippet}\n\n')
        md = re.sub(r'[ \t]+\n', '\n', md)
        md = re.sub(r'\n{3,}', '\n\n', md)
        if '{{<' in md or '{{%' in md:
            md = md.replace('{{<', '{{</*').replace('>}}', '*/>}}').replace('{{%', '{{%/*').replace('%}}', '*/%}}')
        return md.strip()

    def plain(self, html, limit=None):
        text = BeautifulSoup(html or '', 'html.parser').get_text(' ', strip=True)
        text = re.sub(r'\s+', ' ', text).strip()
        if limit and len(text) > limit:
            text = text[:limit].rsplit(' ', 1)[0] + '…'
        return text


